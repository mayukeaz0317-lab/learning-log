// ============================================
// 値の評価と表示(JavaScript Primer)
// ============================================
// エラーは大きく2種類
// - 構文エラー:文法の間違い。実行前に見つかり、ファイル全体が1行も動かない
// - 実行時エラー:文法は正しいが、実行して初めて分かる問題。エラーの行までは実行される
//
// エラーメッセージの読み方
// 例:SyntaxError: missing ) after argument list
//     ^エラーの種類  ^エラー内容の説明
// その後に表示される「ファイル名:行番号:列番号」で、エラーが見つかった位置が分かる

// --------------------------------------------
// 1. 構文エラー(SyntaxError)
// --------------------------------------------
// ※コメントを外すと、ファイル全体が実行されなくなる

// 閉じカッコの付け忘れ
// console.log(1; // => SyntaxError: missing ) after argument list

// const のタイプミス
// cosnt a = 1; // => SyntaxError: Unexpected identifier 'a'

// エラーが指すのは a だが、本当の原因は cosnt のタイプミス
// JavaScriptは左から順に読み、cosnt を「変数名」と解釈する
// 変数名の直後に別の変数名 a が続くのは文法上ありえないので、a の位置でエラーになる
// → エラーの位置と本当の原因はずれることがある。原因は「指された位置か、それより前」にある

// --------------------------------------------
// 2. 実行時エラー(ReferenceError など)
// --------------------------------------------
// ReferenceError:存在しない変数や関数を参照したときのエラー
// よくある原因:変数名のスペルミス、宣言する前に使おうとした

const value = "値";
console.log(value); // => "値"(エラーの手前の行は実行される)

console.log(x); // => ReferenceError: x is not defined
// 本当は value を表示したかったのに、存在しない x を参照してしまった

