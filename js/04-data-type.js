// ============================================
// データ型とリテラル(JavaScript Primer)
// ============================================
// 結論
// - データ型は「7つのプリミティブ型」と「オブジェクト」に分かれる
// - プリミティブ型は値そのものを変更できない(イミュータブル)
//   オブジェクトは作成後も中身を変更できる(ミュータブル)
// - リテラル:値をコードに直接書くための書き方("文字列"、42、[1, 2] など)
// - プリミティブ型の値は、ラッパーオブジェクトを作らずリテラルで書く

// --------------------------------------------
// 1. データ型と typeof
// --------------------------------------------
// プリミティブ型(7種類)
console.log(typeof true); // => "boolean"
console.log(typeof 42); // => "number"
console.log(typeof 9007199254740992n); // => "bigint"
console.log(typeof "JavaScript"); // => "string"
console.log(typeof Symbol("シンボル")); // => "symbol"
console.log(typeof undefined); // => "undefined"
console.log(typeof null); // => "object" ← 歴史的な仕様のバグ。null はプリミティブ型

// オブジェクト(プリミティブ型以外すべて)
console.log(typeof ["配列"]); // => "object"
console.log(typeof { key: "value" }); // => "object"
console.log(typeof function () {}); // => "function" ← 関数だけ特別扱い

// typeof で分かるのは「プリミティブ型か、オブジェクトか」まで
// 配列とオブジェクトの区別はできない

// --------------------------------------------
// 2. 数値リテラル
// --------------------------------------------
console.log(255); // => 255(10進数)
console.log(0b1111); // => 15(2進数:binary)
console.log(0o644); // => 420(8進数:octal)
console.log(0xff); // => 255(16進数:hex。大文字小文字は同じ意味)

console.log(0.123); // => 0.123
// console.log(.123); // 先頭の0は省略できるが、読み間違いを防ぐため省略しない
console.log(2e10); // => 20000000000(2 × 10の10乗)

// _ で桁を区切れる(評価するときは無視される)
console.log(1_000_000_000_000); // => 1000000000000

// 数値で正確に扱える最大の整数は 2^53 - 1
console.log(Number.MAX_SAFE_INTEGER); // => 9007199254740991

// --------------------------------------------
// 3. BigInt:2^53 - 1 より大きい整数を正確に扱う
// --------------------------------------------
console.log(9007199254740992n); // => 9007199254740992n(末尾に n を付ける)
// 1.2n; // => SyntaxError(整数専用なので小数は書けない)

// --------------------------------------------
// 4. 文字列リテラル
// --------------------------------------------
// 3種類あり、評価結果はすべて同じ
console.log("文字列"); // => "文字列"
console.log('文字列'); // => "文字列"
console.log(`文字列`); // => "文字列"

// 囲みと同じ記号を中で使うときは \ でエスケープする
console.log('8 o\'clock'); // => "8 o'clock"
console.log("8 o'clock"); // => "8 o'clock"(別の記号で囲めばエスケープ不要)

// " と ' は改行をそのまま書けないので \n を使う
console.log("複数行の\n文字列"); // => "複数行の\n文字列"

// テンプレートリテラル(`)は改行をそのまま書けて、${} で変数を埋め込める
const str = "文字列";
console.log(`これは${str}です`); // => "これは文字列です"
console.log(`複数行の
文字列`); // => "複数行の\n文字列"

// --------------------------------------------
// 5. null と undefined
// --------------------------------------------
// null:「値がない」ことを表すリテラル
const foo = null;
console.log(foo); // => null

// undefined はリテラルではなく、ただのグローバル変数
// null や true はリテラルなので、変数名には使えない
// let null; // => SyntaxError

// --------------------------------------------
// 6. オブジェクト・配列・正規表現のリテラル
// --------------------------------------------
// オブジェクトリテラル {}
const obj = {
  key: "value",
};
console.log(obj.key); // => "value"(ドット記法)
console.log(obj["key"]); // => "value"(ブラケット記法)

// 配列リテラル []:インデックスは 0 から始まる
const array = ["index:0", "index:1"];
console.log(array[0]); // => "index:0"

// 正規表現リテラル /パターン/
const numberRegExp = /\d+/; // 1文字以上の数字にマッチする
console.log(numberRegExp.test("123")); // => true

// --------------------------------------------
// 7. ラッパーオブジェクト(使わない)
// --------------------------------------------
// new String() で作るとオブジェクトになる
const wrappedStr = new String("文字列");
console.log(typeof wrappedStr); // => "object"
console.log(wrappedStr.length); // => 3

// リテラルのままでも length などのプロパティを使える
// → ラッパーオブジェクトを自分で作る理由はない
const primitiveStr = "文字列";
console.log(typeof primitiveStr); // => "string"
console.log(primitiveStr.length); // => 3